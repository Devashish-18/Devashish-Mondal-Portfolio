

// ===== Dark Mode Toggle =====
const themeToggle = document.getElementById('themeToggle');
const savedTheme = localStorage.getItem('theme') || 'light';

// Apply saved theme on page load
if (savedTheme === 'dark') {
    document.body.classList.add('dark-mode');
    if (themeToggle) {
        themeToggle.querySelector('i').classList.remove('fa-moon');
        themeToggle.querySelector('i').classList.add('fa-sun');
    }
}

// Add theme toggle click handler
if (themeToggle) {
    themeToggle.addEventListener('click', () => {
        document.body.classList.toggle('dark-mode');
        const isDarkMode = document.body.classList.contains('dark-mode');
        localStorage.setItem('theme', isDarkMode ? 'dark' : 'light');
        
        // Update icon
        const icon = themeToggle.querySelector('i');
        if (isDarkMode) {
            icon.classList.remove('fa-moon');
            icon.classList.add('fa-sun');
        } else {
            icon.classList.remove('fa-sun');
            icon.classList.add('fa-moon');
        }
    });
}

// ===== Skill Progress Bar Animation =====
function triggerProgressBars() {
    const progressFills = document.querySelectorAll('.skill-progress-fill');
    progressFills.forEach(fill => {
        fill.style.animation = 'none';
        // Trigger reflow to restart animation
        void fill.offsetWidth;
        fill.style.animation = '';
    });
}

// Use Intersection Observer to trigger progress bars when skills section comes into view
const skillsSection = document.querySelector('#skills');
if (skillsSection) {
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting && !entry.target.dataset.animated) {
                triggerProgressBars();
                entry.target.dataset.animated = 'true';
            }
        });
    }, { threshold: 0.3 });
    
    observer.observe(skillsSection);
}

